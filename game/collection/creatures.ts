export const TOTAL_COLLECTION_COUNT = CREATURES.length;

export const CREATURES_BY_ID: Readonly<Record<string, CreatureDefinition>> =
  Object.fromEntries(CREATURES.map((creature) => [creature.id, creature]));

export const RARITY_COLORS: Record<CreatureRarity, string> = {
  COMMON: '#8A735E',
  UNCOMMON: '#62A77D',
  RARE: '#5C91C9',
  EPIC: '#9871C2',
  LEGENDARY: '#D39A28',
  SECRET: '#D97A72',
};

export function getCreatureById(id: string): CreatureDefinition | undefined {
  return CREATURES_BY_ID[id];
}

export function getCreaturesByRarity(rarity: CreatureRarity): readonly CreatureDefinition[] {
  return CREATURES.filter((creature) => creature.rarity === rarity);
}

function validateCreatureRegistry(): void {
  if (CREATURES.length !== 30) throw new Error('Creature registry must contain 30 entries.');

  const ids = new Set<string>();
  const collectionNumbers = new Set<number>();

  CREATURES.forEach((creature, index) => {
    const expectedNumber = index + 1;
    if (creature.collectionNumber !== expectedNumber) {
      throw new Error(`Creature collection number must be ${expectedNumber}: ${creature.id}`);
    }
    if (ids.has(creature.id)) throw new Error(`Duplicate creature id: ${creature.id}`);
    if (collectionNumbers.has(creature.collectionNumber)) {
      throw new Error(`Duplicate collection number: ${creature.collectionNumber}`);
    }
    if (creature.image === null || creature.image === undefined) {
      throw new Error(`Creature image is missing: ${creature.id}`);
    }
    if (creature.thumbnail === null || creature.thumbnail === undefined) {
      throw new Error(`Creature thumbnail is missing: ${creature.id}`);
    }

    ids.add(creature.id);
    collectionNumbers.add(creature.collectionNumber);
  });
}

if (__DEV__) validateCreatureRegistry();
